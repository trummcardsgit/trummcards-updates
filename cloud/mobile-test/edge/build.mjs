// This packaging step bundles static PWA resources as literals inside one Supabase Edge Function.
// Why: Edge Functions deploy API supports TypeScript source files, not arbitrary static binary assets.
// The generated index.ts can be deployed without a Docker build or a separate site host.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,dirname,basename} from 'node:path';
const root=resolve(import.meta.dirname,'..','web');
const items=['index.html','styles.css','app.js','manifest.webmanifest','sw.js','icon.svg'];
const assets=Object.fromEntries(items.map(p=>[p,readFileSync(resolve(root,p),'utf8')]));
const png=Object.fromEntries([180,192,512].map(i=>[`icon-${i}.png`,readFileSync(resolve(root,`icon-${i}.png`)).toString('base64')]));
const content = `// Generated by edge/build.mjs. Do not hand-edit; edit web/* source instead.
// Static shell is publicly readable. ALL personal account/data operations require
// Supabase JWT + RLS; /api/session performs custom bearer-token authorization.
const assets: Record<string,string> = ${JSON.stringify(assets)};
const png: Record<string,string> = ${JSON.stringify(png)};
const projectRef='cpycfxolqpidfjbhhsmr';
const origin='https://' + projectRef + '.supabase.co';
const slug='trummcards-mobile-test';
const basePath='/functions/v1/' + slug + '/';
const headers={
 'X-Content-Type-Options':'nosniff',
 'Referrer-Policy':'no-referrer',
 'X-Frame-Options':'DENY',
 'Cross-Origin-Resource-Policy':'same-origin',
 'Permissions-Policy':'camera=(self), microphone=(), geolocation=()',
 'Strict-Transport-Security':'max-age=31536000; includeSubDomains',
 'Content-Security-Policy':"default-src 'self'; connect-src 'self' https://"+projectRef+".supabase.co; img-src 'self' data: blob:; style-src 'self'; script-src 'self'; font-src 'self'; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'"
};
function answer(body:string | Uint8Array,contentType:string,additional:Record<string,string>={}) {
 return new Response(body,{headers:{...headers,'Content-Type':contentType,'Cache-Control':'no-store',...additional}});
}
function errJson(error:string,status=401){return new Response(JSON.stringify({error}),{status,headers:{...headers,'Content-Type':'application/json; charset=utf-8','Cache-Control':'no-store'}});}
Deno.serve(async (req:Request)=>{
 const url=new URL(req.url);
 // Supabase gateways can forward either the complete external path, the
 // function slug prefix, or only the subpath (e.g. "/" or "/styles.css").
 // The previous implementation accepted only the full external prefix and
 // returned a 404 for valid requests after the gateway stripped that prefix.
 if(req.method!=='GET')return errJson('Method not allowed',405);
 if(url.pathname===basePath.slice(0,-1)||url.pathname==='/'+slug){
   return Response.redirect(origin+basePath,308);
 }
 const prefixes=[basePath,'/'+slug+'/'];
 const prefix=prefixes.find(p=>url.pathname.startsWith(p));
 const target=prefix?url.pathname.slice(prefix.length):url.pathname.startsWith('/')?url.pathname.slice(1):null;
 if(target===null)return errJson('Not found',404);
 if(target==='api/config'){
  const anon=Deno.env.get('SUPABASE_ANON_KEY');
  if(!anon)return errJson('Supabase publishable configuration unavailable',503);
  return answer(JSON.stringify({url:origin,project_ref:projectRef,anon_key:anon}),'application/json; charset=utf-8');
 }
 if(target==='api/session') {
   // Authenticated health endpoint demonstrating custom bearer verification. It
   // never uses a service-role key. All actual stock operations use DB RLS RPC.
   const token=req.headers.get('Authorization')?.match(/^Bearer (.+)$/i)?.[1];
   if(!token)return errJson('Authentication required');
   const anon=Deno.env.get('SUPABASE_ANON_KEY');if(!anon)return errJson('Server not configured',503);
   const me=await fetch(origin+'/auth/v1/user',{headers:{apikey:anon,Authorization:'Bearer '+token}});
   if(!me.ok)return errJson('Invalid session');
   const owner=await fetch(origin+'/rest/v1/rpc/tc_is_authorized',{method:'POST',headers:{apikey:anon,Authorization:'Bearer '+token,'Content-Type':'application/json'},body:'{}'});
   if(!owner.ok||await owner.json()!==true)return errJson('Not authorized',403);
   return answer(JSON.stringify({authorized:true}),'application/json; charset=utf-8');
 }
 if(target==='sw.js')return answer(assets['sw.js'],'text/javascript; charset=utf-8',{'Service-Worker-Allowed':basePath});
 if(target==='manifest.webmanifest')return answer(assets[target],'application/manifest+json; charset=utf-8');
 if(target.startsWith('icon-')&&Object.hasOwn(png,target)){
   const decoded=atob(png[target]); const bytes=Uint8Array.from(decoded,c=>c.charCodeAt(0));return answer(bytes,'image/png');
 }
 if(target==='icon.svg')return answer(assets[target],'image/svg+xml; charset=utf-8');
 if(target==='app.js')return answer(assets[target],'text/javascript; charset=utf-8');
 if(target==='styles.css')return answer(assets[target],'text/css; charset=utf-8');
 if(target===''||target==='index.html')return answer(assets['index.html'],'text/html; charset=utf-8');
 return errJson('Not found',404);
});
`;
const out=resolve(import.meta.dirname,'index.ts');writeFileSync(out,content);console.log('Bundled Edge PWA:',out,content.length,'bytes');
